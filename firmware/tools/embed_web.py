# PlatformIO pre-build step: embeds gzipped web/index.html and web/teams.json
# into src/web_page.h, so there's no separate filesystem upload step.
import gzip, os

try:
    Import("env")  # noqa: F821  (provided by PlatformIO/SCons)
    root = env["PROJECT_DIR"]  # noqa: F821
except NameError:
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def gz(name):
    return gzip.compress(open(os.path.join(root, "web", name), "rb").read(), 9, mtime=0)


def arr(name, data):
    rows = ",\n".join(",".join("0x%02x" % b for b in data[i : i + 24]) for i in range(0, len(data), 24))
    return "static const unsigned char %s[] PROGMEM = {\n%s\n};\nstatic const size_t %s_LEN = %d;\n" % (
        name, rows, name, len(data))


html, teams = gz("index.html"), gz("teams.json")
out = (
    "// AUTO-GENERATED by tools/embed_web.py from web/index.html + web/teams.json. Don't edit.\n"
    "#pragma once\n#include <pgmspace.h>\n#include <stddef.h>\n"
    + arr("INDEX_HTML_GZ", html) + arr("TEAMS_JSON_GZ", teams)
)
dst = os.path.join(root, "src", "web_page.h")
if not os.path.exists(dst) or open(dst, encoding="utf-8").read() != out:
    open(dst, "w", encoding="utf-8").write(out)
    print("embed_web: wrote src/web_page.h (index.html.gz %d B, teams.json.gz %d B)" % (len(html), len(teams)))
