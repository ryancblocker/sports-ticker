#!/usr/bin/env python3
"""Generate anti-aliased Inter + Anton fonts for the ticker (LovyanGFX / TFT_eSPI "VLW" format).

    python3 -m pip install freetype-py
    python3 tools/make_fonts.py

Writes src/fonts_inter.h (declarations) and src/fonts_inter.cpp (data). Only needed when changing font sizes; the output is committed.
"""
import os, struct
import freetype

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ASCII = [chr(c) for c in range(0x20, 0x7F)]
EXTRA = ["·", "–", "’", "“", "”", "…", "°"]
DIGITS = list(" 0123456789-:.")
CAPS = list(" !-0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ")

# name, ttf, pixel size, glyphs
FONTS = [
    ("INTER_11", "Inter-SemiBold.ttf", 11, ASCII + EXTRA),
    ("INTER_12", "Inter-Medium.ttf", 12, ASCII + EXTRA),
    ("INTER_13", "Inter-SemiBold.ttf", 13, ASCII + EXTRA),
    ("INTER_13B", "Inter-Bold.ttf", 13, ASCII + EXTRA),
    ("INTER_15", "Inter-Bold.ttf", 15, ASCII + EXTRA),
    ("INTER_17", "Inter-Bold.ttf", 17, ASCII + EXTRA),
    ("INTER_30", "Inter-Bold.ttf", 30, ASCII + EXTRA),
    ("INTER_40", "Inter-Bold.ttf", 40, DIGITS),
    # score-alert headline ("TOUCHDOWN"): Anton, a heavy condensed scoreboard face (OFL)
    ("ANTON_44", "Anton-Regular.ttf", 44, CAPS),
]


def vlw(ttf, px, chars):
    face = freetype.Face(os.path.join(ROOT, "fonts", ttf))
    face.set_pixel_sizes(0, px)
    glyphs = []
    for ch in sorted(set(chars), key=ord):
        face.load_char(ch, freetype.FT_LOAD_RENDER | freetype.FT_LOAD_TARGET_NORMAL)
        g = face.glyph
        bm = g.bitmap
        w, h = bm.width, bm.rows
        data = bytearray()
        for r in range(h):
            data += bytes(bm.buffer[r * bm.pitch : r * bm.pitch + w])
        if ch == " ":
            w = h = 0
            data = bytearray()
        glyphs.append((ord(ch), h, w, round(g.advance.x / 64), g.bitmap_top, g.bitmap_left, bytes(data)))

    def metric(ch, f):
        face.load_char(ch, freetype.FT_LOAD_RENDER)
        return f(face.glyph)

    ascent = metric("d", lambda g: g.bitmap_top) if "d" in chars else metric("0", lambda g: g.bitmap_top)
    descent = metric("p", lambda g: g.bitmap.rows - g.bitmap_top) if "p" in chars else 0
    out = bytearray(struct.pack(">6i", len(glyphs), 11, px, 0, ascent, descent))
    for (u, h, w, adv, dy, dx, _) in glyphs:
        out += struct.pack(">7i", u, h, w, adv, dy, dx, 0)
    for g in glyphs:
        out += g[6]
    return bytes(out)


HDR = "// AUTO-GENERATED by tools/make_fonts.py from Inter and Anton (SIL Open Font License, see fonts/).\n"
decl = [HDR, "#pragma once", "#include <stdint.h>", ""]
defs = [HDR, '#include "fonts_inter.h"', "#include <pgmspace.h>", ""]
total = 0
for name, ttf, px, chars in FONTS:
    data = vlw(ttf, px, chars)
    total += len(data)
    rows = ",\n".join(",".join("%d" % b for b in data[i:i + 40]) for i in range(0, len(data), 40))
    decl.append("extern const uint8_t %s[];  // %s %dpx" % (name, ttf[:-4], px))
    defs.append("const uint8_t %s[] PROGMEM = {\n%s\n};" % (name, rows))
    print("%-10s %-20s %2dpx %6d bytes" % (name, ttf, px, len(data)))
open(os.path.join(ROOT, "src", "fonts_inter.h"), "w").write("\n".join(decl) + "\n")
open(os.path.join(ROOT, "src", "fonts_inter.cpp"), "w").write("\n".join(defs) + "\n")
print("total", total, "bytes -> src/fonts_inter.{h,cpp}")
